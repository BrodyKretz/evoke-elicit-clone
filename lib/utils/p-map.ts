// Bounded-parallelism map. Runs `fn` over `items` with at most `concurrency`
// concurrent calls. Preserves output order. Extracted out of screen.ts /
// extract.ts after the third copy showed up.
export async function pMap<T, U>(
  items: T[],
  concurrency: number,
  fn: (item: T, index: number) => Promise<U>
): Promise<U[]> {
  const results: U[] = new Array(items.length);
  let next = 0;
  const workers = Array.from(
    { length: Math.min(concurrency, items.length) },
    async () => {
      while (true) {
        const i = next++;
        if (i >= items.length) return;
        results[i] = await fn(items[i], i);
      }
    }
  );
  await Promise.all(workers);
  return results;
}
