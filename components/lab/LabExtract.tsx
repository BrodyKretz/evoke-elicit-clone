"use client";

import Link from "next/link";
import { useEffect, useState } from "react";
import type { Paper } from "@/lib/types";
import { Book, Grid, Search, User } from "@/components/ui/Icon";
import { useToast } from "@/components/ui/Toast";
import { getSelectedPapers, subscribeSelection } from "@/lib/lab/selection";

type ExtractRow = {
  paperId: string;
  paperTitle: string;
  paperYear: number;
  paperAuthors: string[];
  cells: string[];
  evidence?: { quotes: string[] }[];
};

type ExtractResult = {
  columns: string[];
  rows: ExtractRow[];
  skipped: number;
};

export function LabExtract() {
  const { show } = useToast();
  const [papers, setPapers] = useState<Paper[]>([]);
  const [question, setQuestion] = useState("");
  const [running, setRunning] = useState(false);
  const [result, setResult] = useState<ExtractResult | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const refresh = () => setPapers(getSelectedPapers());
    refresh();
    return subscribeSelection(refresh);
  }, []);

  const run = async () => {
    const q = question.trim();
    if (!q || running || papers.length === 0) return;
    setRunning(true);
    setError(null);
    setResult(null);
    try {
      const res = await fetch("/api/lab/extract", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ papers, question: q }),
      });
      const body = (await res.json().catch(() => ({}))) as ExtractResult & { error?: string };
      if (!res.ok) {
        setError(body.error ?? "Extraction failed");
        return;
      }
      setResult(body);
      if (body.skipped > 0) {
        show(`${body.skipped} paper(s) skipped — no abstract available`);
      }
    } catch {
      setError("Network error.");
    } finally {
      setRunning(false);
    }
  };

  if (papers.length === 0) {
    return (
      <div className="mx-auto max-w-3xl px-8 py-12">
        <div className="mb-2 inline-flex items-center gap-1.5 rounded-full border border-transparent bg-[#2A2A2A] px-2.5 py-0.5 text-[11px] uppercase tracking-wider text-[#B4B4B4]">
          Lab · Tool
        </div>
        <h1 className="mb-3 font-display text-3xl font-medium tracking-tight text-[#ECECEC]">
          Extract data
        </h1>
        <p className="mb-6 max-w-2xl text-[14px] leading-relaxed text-[#B4B4B4]">
          You haven&apos;t selected any papers yet. Go to{" "}
          <Link href="/lab/find" className="font-medium text-[#ECECEC] hover:underline">
            Find papers
          </Link>{" "}
          and check the boxes next to papers you want to extract from.
        </p>
        <Link
          href="/lab/find"
          className="inline-flex items-center gap-1 rounded-md border border-[#0D0D0D] bg-[#0D0D0D] px-3 py-1.5 text-[13px] font-medium text-white hover:bg-[#202020]"
        >
          <Search size={12} /> Find papers
        </Link>
      </div>
    );
  }

  return (
    <div className="mx-auto max-w-6xl px-8 py-8">
      <div className="mb-1 inline-flex items-center gap-1.5 self-start rounded-full border border-transparent bg-[#2A2A2A] px-2.5 py-0.5 text-[11px] uppercase tracking-wider text-[#B4B4B4]">
        Lab · Tool
      </div>
      <h1 className="mb-2 font-display text-2xl font-medium tracking-tight text-[#ECECEC]">
        Extract data from {papers.length} paper{papers.length === 1 ? "" : "s"}
      </h1>
      <p className="mb-5 max-w-2xl text-[13px] text-[#B4B4B4]">
        Columns are auto-generated by Sonnet 4.6 from your guiding question, then each
        paper&apos;s abstract is parsed into row values with per-cell evidence quotes.
      </p>

      <form
        onSubmit={(e) => {
          e.preventDefault();
          run();
        }}
        className="mb-6 flex items-center gap-2 rounded-full border border-transparent bg-[#2A2A2A] px-4 py-2 shadow-sm"
      >
        <Grid size={14} className="flex-shrink-0 text-[#B4B4B4]" />
        <input
          value={question}
          onChange={(e) => setQuestion(e.target.value)}
          placeholder="What question is this extraction meant to answer? (guides which columns get generated)"
          className="flex-1 bg-transparent text-[14px] outline-none placeholder:text-[#8E8E8E]"
          disabled={running}
        />
        <button
          type="submit"
          disabled={!question.trim() || running}
          className="rounded-full bg-[#ECECEC] px-4 py-1.5 text-[13px] font-medium text-[#0D0D0D] hover:bg-white disabled:opacity-50"
        >
          {running ? "Extracting…" : "Run extract"}
        </button>
      </form>

      {error && (
        <div className="mb-6 rounded-[10px] bg-[#3A1F1F] px-4 py-3 text-sm text-[#FF6B6B]">
          {error}
        </div>
      )}

      {running && (
        <div className="mb-6 rounded-[10px] border border-transparent bg-[#2A2A2A] px-4 py-6 text-center text-sm text-[#B4B4B4]">
          Running Sonnet 4.6 against {papers.length} paper{papers.length === 1 ? "" : "s"}…
        </div>
      )}

      {result && (
        <div className="overflow-x-auto rounded-[10px] border border-transparent bg-[#2A2A2A]">
          <table className="w-full text-[12.5px]">
            <thead>
              <tr className="border-b border-transparent bg-[#2F2F2F] text-left">
                <th className="px-3 py-2.5 font-semibold text-[#ECECEC]">Paper</th>
                {result.columns.map((c) => (
                  <th key={c} className="px-3 py-2.5 font-semibold text-[#ECECEC]">
                    {c}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {result.rows.map((row) => (
                <tr key={row.paperId} className="border-b border-transparent last:border-b-0">
                  <td className="px-3 py-3 align-top">
                    <div className="font-medium text-[#ECECEC]">{row.paperTitle}</div>
                    <div className="mt-0.5 text-[#B4B4B4]">
                      <User size={9} className="mr-1 inline" />
                      {row.paperAuthors.slice(0, 2).join(", ")}
                      {row.paperAuthors.length > 2 ? " et al." : ""} ·{" "}
                      <Book size={9} className="ml-1 mr-0.5 inline" />
                      {row.paperYear || "n.d."}
                    </div>
                  </td>
                  {row.cells.map((cell, i) => {
                    const quotes = row.evidence?.[i]?.quotes ?? [];
                    return (
                      <td key={i} className="px-3 py-3 align-top text-[#ECECEC]">
                        <div className="whitespace-pre-wrap">{cell}</div>
                        {quotes.length > 0 && (
                          <details className="mt-1.5 text-[#B4B4B4]">
                            <summary className="cursor-pointer text-[11px] font-medium text-[#ECECEC] hover:underline">
                              {quotes.length} quote{quotes.length === 1 ? "" : "s"} from abstract
                            </summary>
                            <ul className="mt-1 space-y-1 pl-2 text-[11.5px] italic">
                              {quotes.map((qq, j) => (
                                <li key={j}>&ldquo;{qq}&rdquo;</li>
                              ))}
                            </ul>
                          </details>
                        )}
                      </td>
                    );
                  })}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
